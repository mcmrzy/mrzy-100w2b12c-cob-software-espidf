/* ======================== 内联转换函数 ======================== */

/**
 * @brief 将色温值转换为查找表索引
 * @param cct 色温值 (2700 ~ 6500 K)
 * @return 查找表索引 (0 ~ 37)，超出范围时钳位
 */
static inline uint8_t cct_to_index(uint16_t cct)
{
    if (cct <= 2700) return 0;
    if (cct >= 6500) return CCT_TABLE_STEPS - 1;

    /* 线性映射: index = (cct - 2700) / 100 */
    uint8_t idx = (uint8_t)((cct - 2700) / 100);

    /* 钳位到有效范围 */
    if (idx >= CCT_TABLE_STEPS) {
        idx = CCT_TABLE_STEPS - 1;
    }

    return idx;
}

/**
 * @brief 将查找表索引转换为色温值
 * @param idx 查找表索引 (0 ~ 37)
 * @return 色温值 (K)，超出范围时返回默认值 4600K
 */
static inline uint16_t index_to_cct(uint8_t idx)
{
    if (idx >= CCT_TABLE_STEPS) {
        return 4600;  /* CCT_DEFAULT */
    }
    return CCT_VALUE_TABLE[idx];
}

